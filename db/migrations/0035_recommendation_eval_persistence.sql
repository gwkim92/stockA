alter table ai.eval_run
    add column if not exists pipeline_run_id bigint references ops.pipeline_run (run_id) on delete set null,
    add column if not exists as_of_date date,
    add column if not exists horizon_days integer,
    add column if not exists config_json jsonb;

create index if not exists ai_eval_run_pipeline_run_id_idx
    on ai.eval_run (pipeline_run_id)
    where pipeline_run_id is not null;

create index if not exists ai_eval_run_as_of_date_idx
    on ai.eval_run (eval_name, as_of_date desc, created_at desc)
    where as_of_date is not null;

create table if not exists ai.recommendation_eval_snapshot (
    snapshot_id bigint generated always as identity primary key,
    eval_run_id bigint not null references ai.eval_run (eval_run_id) on delete cascade,
    snapshot_schema_version text not null,
    source_recommendation_id bigint not null,
    source_batch_id bigint not null,
    source_thesis_id bigint,
    source_outcome_id bigint,
    primary_symbol text not null,
    recommendation_action text not null,
    recommendation_total_score numeric(8,4) not null,
    selected_outcome_alpha_pct numeric(12,6),
    snapshot_json jsonb not null,
    snapshot_sha256 text not null,
    created_at timestamptz not null default now(),
    unique (eval_run_id, source_recommendation_id),
    check (length(snapshot_schema_version) > 0),
    check (length(primary_symbol) > 0),
    check (length(recommendation_action) > 0),
    check (snapshot_sha256 ~ '^[0-9a-f]{64}$')
);

create index if not exists recommendation_eval_snapshot_recommendation_idx
    on ai.recommendation_eval_snapshot (source_recommendation_id, created_at desc);

create index if not exists recommendation_eval_snapshot_batch_idx
    on ai.recommendation_eval_snapshot (source_batch_id, created_at desc);

create index if not exists recommendation_eval_snapshot_outcome_idx
    on ai.recommendation_eval_snapshot (source_outcome_id)
    where source_outcome_id is not null;

comment on table ai.recommendation_eval_snapshot is
    'Append-only recommendation source state frozen at an ai.eval_run. Source IDs are historical values, intentionally not cascading foreign keys.';

comment on column ai.recommendation_eval_snapshot.snapshot_sha256 is
    'SHA-256 of canonical UTF-8 JSON generated by the recommendation quality evaluator.';
